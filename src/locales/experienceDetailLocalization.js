function mapObjectList(baseList, localizedList) {
  const base = Array.isArray(baseList) ? baseList : [];
  const localized = Array.isArray(localizedList) ? localizedList : [];
  return base.map((item, index) => ({
    ...item,
    ...(localized[index] || {}),
  }));
}

function mapFaqList(baseList, localizedList, lang) {
  const base = Array.isArray(baseList) ? baseList : [];
  const localized = Array.isArray(localizedList) ? localizedList : [];

  return base.map((item, index) => {
    const localizedFaq = localized[index] || {};
    const merged = {
      ...item,
      ...localizedFaq,
    };

    if (item?.link) {
      merged.link = {
        ...item.link,
        ...(localizedFaq.link || {}),
        href: `/${lang}/policy`,
      };
    }

    return merged;
  });
}

export function localizeRainbowTourContent(lang, base) {
  if (!TARGET_LANGUAGES.has(lang)) return base;

  const localized = rainbowTourText[lang];
  if (!localized) return base;

  return {
    ...base,
    ...localized,
    stops: mapObjectList(base.stops, localized.stops),
    departureProfiles: mapObjectList(base.departureProfiles, localized.departureProfiles).map((profile, profileIndex) => ({
      ...profile,
      points: mapObjectList(base.departureProfiles?.[profileIndex]?.points, localized.departureProfiles?.[profileIndex]?.points),
    })),
    faqs: mapFaqList(base.faqs, localized.faqs, lang),
  };
}

export function localizeExperienceDetail(lang, experienceId, base) {
  if (!base || !TARGET_LANGUAGES.has(lang)) return base;

  const localized = experienceDetailText[lang]?.[experienceId];
  if (!localized) return base;

  return {
    ...base,
    ...localized,
    faqs: mapFaqList(base.faqs, localized.faqs, lang),
    ports: mapObjectList(base.ports, localized.ports),
    sources: mapObjectList(base.sources, localized.sources),
  };
}